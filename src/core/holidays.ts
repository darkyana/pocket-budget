import { dayKeyOf } from './time'

/**
 * 中国法定节假日：休息日区间 + 调休上班日。
 * 数据来源：国务院办公厅《关于2026年部分节假日安排的通知》
 * （国办发明电〔2025〕7号，2025-11-04 发布）。
 * 每年 11~12 月国务院发布次年安排后在此追加新表；表未覆盖的日期一律退回
 * 「周六周日 = 休」的朴素规则，宁可少认假也不猜错。
 */
const REST_2026: ReadonlyArray<readonly [string, string]> = [
  ['2026-01-01', '2026-01-03'], // 元旦
  ['2026-02-15', '2026-02-23'], // 春节
  ['2026-04-04', '2026-04-06'], // 清明
  ['2026-05-01', '2026-05-05'], // 劳动
  ['2026-06-19', '2026-06-21'], // 端午
  ['2026-09-25', '2026-09-27'], // 中秋
  ['2026-10-01', '2026-10-07'], // 国庆
]
const WORK_2026: readonly string[] = [
  '2026-01-04', // 元旦调休
  '2026-02-14', '2026-02-28', // 春节调休
  '2026-05-09', // 劳动节调休
  '2026-09-20', '2026-10-10', // 国庆调休
]

/** 休息日 = 法定节假日（含调休拼出的连休）或普通周末；调休上班的周末不算休 */
export function isRestDay(d: Date): boolean {
  const k = dayKeyOf(d)
  if (WORK_2026.includes(k)) return false
  if (REST_2026.some(([a, b]) => a <= k && k <= b)) return true
  const wd = d.getDay()
  return wd === 0 || wd === 6
}
